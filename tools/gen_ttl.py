"""Generate the complete permanent Loo-pi port metadata (no dependencies)."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
URI = "https://github.com/ABustos2606/loo-pi#loopi"
PORTS = []


def port(symbol, name, kind, lo=None, hi=None, default=None, props=(), unit=None, labels=()):
    PORTS.append(dict(symbol=symbol, name=name, kind=kind, lo=lo, hi=hi,
                      default=default, props=props, unit=unit, labels=labels))


def toggle(symbol, name, default=0, trigger=False):
    port(symbol, name, "control_in", 0, 1, default,
         ("lv2:toggled", "lv2:integer") + (("pprops:trigger",) if trigger else ()))


for symbol, name, kind in [("in_l", "In L", "audio_in"), ("in_r", "In R", "audio_in"),
                           ("out_l", "Out L", "audio_out"), ("out_r", "Out R", "audio_out"),
                           ("commands", "Commands", "atom_in")]:
    port(symbol, name, kind)
for symbol, name in [("rec_dub", "Rec/Dub"), ("overdub", "Overdub"), ("undo", "Undo"),
                     ("mute", "Mute"), ("trigger", "Play"), ("pause", "Pause"), ("next_loop", "Next loop")]:
    toggle(symbol, name, trigger=True)
port("dry_level", "Dry level", "control_in", 0, 1, 1)
port("loops", "Loops", "control_in", 1, 8, 1, ("lv2:integer",))
port("selected", "Selected loop", "control_in", 1, 8, 1, ("lv2:integer",))
port("quantize", "Quantize", "control_in", 0, 3, 0, ("lv2:integer", "lv2:enumeration"),
     labels=("Off", "Cycle", "8th", "Loop"))
for symbol, name in [("round", "Round"), ("mute_quant", "Mute quantized"),
                     ("dub_quant", "Dub quantized"), ("repl_quant", "Repl quantized")]:
    toggle(symbol, name)
port("sync_to", "Sync to", "control_in", 0, 9, 0, ("lv2:integer", "lv2:enumeration"),
     labels=("None", "Tempo", *(f"Loop {n}" for n in range(1, 9))))
toggle("rel_sync", "Relative sync")
port("eighths", "8ths/cycle", "control_in", 1, 128, 16, ("lv2:integer",))
port("bpm", "BPM", "control_in", 30, 300, 120, unit="bpm")
port("fade", "Fade ms", "control_in", 0, 50, 1.3, unit="ms")
toggle("safety_fb", "Safe feedback", 1)
port("loop_secs", "Loop memory", "control_in", 10, 300, 40, unit="s")
toggle("enabled", "On", 1)
port("selected_out", "Selected", "control_out", 1, 8, props=("lv2:integer",))
port("soloed", "Soloed", "control_out", 0, 8, props=("lv2:integer",))
# The core rounds memory up to a power of two: 300 s can become almost 600 s.
port("free_mem", "Free memory", "control_out", 0, 600, unit="s")
port("cycle_clock", "Cycle clock", "cv_out", 0, 1)
port("loop_clock", "Loop clock", "cv_out", 0, 1)
for n in range(1, 9):
    prefix, name = f"l{n}_", f"L{n} "
    for suffix, label, default in [("level", "Level", 1), ("in_gain", "Input gain", 1),
                                    ("thresh", "Threshold", 0), ("feedback", "Feedback", 1)]:
        port(prefix + suffix, name + label, "control_in", 0, 1, default)
    for suffix, label in [("sync", "Sync"), ("play_sync", "Play sync"), ("play_fb", "Play feedbk")]:
        toggle(prefix + suffix, name + label)
    port(prefix + "rate", name + "Rate", "control_in", 0.25, 4, 1, ("pprops:logarithmic",))
    port(prefix + "state", name + "State", "control_out", -2, 20, props=("lv2:integer",))
    port(prefix + "next", name + "Next state", "control_out", -2, 20, props=("lv2:integer",))
    port(prefix + "waiting", name + "Waiting", "control_out", 0, 1, props=("lv2:toggled", "lv2:integer"))
    for suffix, label in [("len", "Length"), ("cycle", "Cycle"), ("pos", "Position")]:
        port(prefix + suffix, name + label, "control_out", 0, 600, unit="s")

PREFIXES = '''# SPDX-License-Identifier: GPL-2.0-or-later
# Copyright (c) 2026 Alejandro Bustos
# Generated by tools/gen_ttl.py; edit the table there.
@prefix atom: <http://lv2plug.in/ns/ext/atom#> .
@prefix doap: <http://usefulinc.com/ns/doap#> .
@prefix foaf: <http://xmlns.com/foaf/0.1/> .
@prefix lv2: <http://lv2plug.in/ns/lv2core#> .
@prefix opts: <http://lv2plug.in/ns/ext/options#> .
@prefix bufsz: <http://lv2plug.in/ns/ext/buf-size#> .
@prefix pprops: <http://lv2plug.in/ns/ext/port-props#> .
@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .
@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .
@prefix rsz: <http://lv2plug.in/ns/ext/resize-port#> .
@prefix state: <http://lv2plug.in/ns/ext/state#> .
@prefix units: <http://lv2plug.in/ns/extensions/units#> .
@prefix urid: <http://lv2plug.in/ns/ext/urid#> .
@prefix work: <http://lv2plug.in/ns/ext/worker#> .
'''


def turtle():
    result = PREFIXES + f'''
<{URI}>
    a lv2:Plugin, lv2:DelayPlugin ;
    doap:name "Loo-pi" ;
    doap:license <https://spdx.org/licenses/GPL-2.0-or-later> ;
    doap:description "Stereo looper for Peepo, based on SooperLooper by Jesse Chappell. Up to eight stereo loops with every SooperLooper command, quantize, sync to tempo or to a loop, varispeed and clock outputs. Loops are saved with the patch." ;
    doap:homepage <https://github.com/ABustos2606/loo-pi> ;
    doap:maintainer [ a foaf:Person ; foaf:name "Alejandro Bustos" ;
        foaf:homepage <https://github.com/ABustos2606> ] ;
    doap:developer [ a foaf:Person ; foaf:name "Jesse Chappell" ;
        foaf:homepage <https://essej.net/sooperlooper/> ] ;
    lv2:minorVersion 4 ; lv2:microVersion 0 ;
    lv2:requiredFeature urid:map, work:schedule ;
    lv2:optionalFeature lv2:hardRTCapable, opts:options, state:mapPath, state:makePath, state:freePath ;
    opts:supportedOption bufsz:nominalBlockLength, bufsz:maxBlockLength ;
    lv2:extensionData work:interface, state:interface ;
    lv2:port
'''
    blocks = []
    for index, p in enumerate(PORTS):
        kind, direction = p["kind"].split("_")
        cls = {"audio": "lv2:AudioPort", "control": "lv2:ControlPort", "cv": "lv2:CVPort", "atom": "atom:AtomPort"}[kind]
        fields = [f'a lv2:{"InputPort" if direction == "in" else "OutputPort"}, {cls}',
                  f'lv2:index {index}', f'lv2:symbol "{p["symbol"]}"', f'lv2:name "{p["name"]}"']
        for key, predicate in [("lo", "minimum"), ("hi", "maximum"), ("default", "default")]:
            if p[key] is not None:
                fields.append(f'lv2:{predicate} {p[key]}')
        if p["props"]:
            fields.append("lv2:portProperty " + ", ".join(p["props"]))
        if p["unit"]:
            fields.append("units:unit units:" + p["unit"])
        if p["symbol"] == "enabled":
            fields.append("lv2:designation lv2:enabled")
        if kind == "atom":
            fields += ["atom:bufferType atom:Sequence", "atom:supports atom:Int", "rsz:minimumSize 4096"]
        if p["labels"]:
            fields.append("lv2:scalePoint " + ", ".join(
                f'[ rdfs:label "{label}" ; rdf:value {value} ]' for value, label in enumerate(p["labels"])))
        blocks.append("    [ " + " ;\n      ".join(fields) + " ]")
    return result + ",\n".join(blocks) + " .\n"


def header():
    result = '''// SPDX-License-Identifier: GPL-2.0-or-later
// Copyright (c) 2026 Alejandro Bustos
#pragma once
#include <cstdint>

namespace loopi {
inline constexpr char kURI[] = "https://github.com/ABustos2606/loo-pi#loopi";
inline constexpr uint32_t kMaxLoops = 8;
inline constexpr uint32_t kLoopBase = 33;
inline constexpr uint32_t kLoopStride = 14;
// Permanent ABI; the kind comments are checked by tests/ttl_check.py.
enum class Port : uint32_t {
'''
    result += "".join(f'    {p["symbol"]} = {i}, // {p["kind"]}\n' for i, p in enumerate(PORTS))
    return result + f'''    count = {len(PORTS)}
}};
constexpr uint32_t index(Port p) {{ return static_cast<uint32_t>(p); }}
static_assert(index(Port::count) == kLoopBase + kMaxLoops * kLoopStride);
}} // namespace loopi
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if checked-in Turtle is stale")
    parser.add_argument("--header", action="store_true", help="also write ports.hpp; review ABI changes carefully")
    args = parser.parse_args()
    path = ROOT / "loo-pi.lv2/loo-pi.ttl"
    if args.check:
        if path.read_text(encoding="utf-8") != turtle():
            raise SystemExit("FAIL: run python3 tools/gen_ttl.py")
    else:
        path.parent.mkdir(exist_ok=True)
        path.write_text(turtle(), encoding="utf-8", newline="\n")
    if args.header:
        (ROOT / "lv2").mkdir(exist_ok=True)
        (ROOT / "lv2/ports.hpp").write_text(header(), encoding="utf-8", newline="\n")
